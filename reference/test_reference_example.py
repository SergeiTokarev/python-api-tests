import requests  # библиотека для HTTP-запросов; в stdlib её нет, ставится из requirements.txt

import config  # наш собственный модуль с BASE_URL и таймаутом


# ─────────────────────────────────────────────────────────────────────────────
# ПРИМЕР 1. Самый простой тест: сервис жив?
# ─────────────────────────────────────────────────────────────────────────────

def test_ping_returns_created():
    """GET /ping отвечает 201 — значит сервис поднят.

    Почему имя функции начинается с test_:
    pytest сам находит тесты по этому префиксу (настроено в pytest.ini,
    параметр python_functions). Переименуешь в check_ping — тест не запустится.

    Почему имя такое длинное:
    при падении pytest печатает имя теста. "test_ping_returns_created"
    в отчёте понятно без открытия кода, а "test_1" — нет.
    """
    # ── Act: выполняем действие, которое проверяем ──
    # timeout обязателен. Без него, если сервис зависнет,
    # тест будет ждать бесконечно и повесит весь прогон.
    response = requests.get(f"{config.BASE_URL}/ping", timeout=config.TIMEOUT)

    # ── Assert: сверяем результат с ожиданием ──
    # Второй аргумент assert — сообщение при падении.
    # Без него в отчёте будет "assert 503 == 201" и всё.
    # С ним — сразу видно, какой был URL и что мы вообще ждали.
    assert response.status_code == 201, (
        f"Ожидали 201 от GET /ping, получили {response.status_code}. "
        f"Тело ответа: {response.text!r}"
    )


# ─────────────────────────────────────────────────────────────────────────────
# ПРИМЕР 2. Тест посложнее: разбираем JSON-ответ
# ─────────────────────────────────────────────────────────────────────────────

def test_booking_list_returns_non_empty_list_of_ids():
    """GET /booking возвращает непустой список объектов с полем bookingid.

    Структура теста — Arrange / Act / Assert (AAA):
      Arrange — подготовить данные и окружение
      Act     — сделать одно проверяемое действие
      Assert  — сверить результат с ожиданием

    Здесь Arrange пустой: ничего готовить не нужно.
    Один тест — одно Act. Если в тесте два действия,
    при падении непонятно, какое из них сломалось.
    """
    # ── Act ──
    response = requests.get(f"{config.BASE_URL}/booking", timeout=config.TIMEOUT)

    # ── Assert ──
    # Сначала проверяем статус. Если он не 200, вызывать .json() бессмысленно:
    # на ошибке сервис мог вернуть HTML или пустое тело, и .json() упадёт
    # с невнятным JSONDecodeError вместо понятного сообщения о статусе.
    assert response.status_code == 200, (
        f"Ожидали 200 от GET /booking, получили {response.status_code}"
    )

    # .json() превращает тело ответа в объекты Python:
    # JSON-массив  → list,  JSON-объект → dict
    bookings = response.json()

    assert isinstance(bookings, list), (
        f"Ожидали список, получили {type(bookings).__name__}"
    )
    assert len(bookings) > 0, "Список бронирований пуст — не на чем проверять остальное"

    # Проверяем структуру первого элемента.
    # Проверять все 1600 смысла нет: это тест API, а не нагрузочный.
    first = bookings[0]
    assert "bookingid" in first, (
        f"В элементе списка нет ключа 'bookingid'. Пришло: {first}"
    )
